// Generates src/content/kana.js systematically so romaji mappings cannot drift by transcription.
const fs = require('fs');
const path = require('path');

const base = [
  ['あ','a'],['い','i'],['う','u'],['え','e'],['お','o'],
  ['か','ka'],['き','ki'],['く','ku'],['け','ke'],['こ','ko'],
  ['さ','sa'],['し','shi'],['す','su'],['せ','se'],['そ','so'],
  ['た','ta'],['ち','chi'],['つ','tsu'],['て','te'],['と','to'],
  ['な','na'],['に','ni'],['ぬ','nu'],['ね','ne'],['の','no'],
  ['は','ha'],['ひ','hi'],['ふ','fu'],['へ','he'],['ほ','ho'],
  ['ま','ma'],['み','mi'],['む','mu'],['め','me'],['も','mo'],
  ['や','ya'],['ゆ','yu'],['よ','yo'],
  ['ら','ra'],['り','ri'],['る','ru'],['れ','re'],['ろ','ro'],
  ['わ','wa'],['を','wo'],['ん','n'],
];
const voiced = [
  ['が','ga'],['ぎ','gi'],['ぐ','gu'],['げ','ge'],['ご','go'],
  ['ざ','za'],['じ','ji'],['ず','zu'],['ぜ','ze'],['ぞ','zo'],
  ['だ','da'],['ぢ','ji'],['づ','zu'],['で','de'],['ど','do'],
  ['ば','ba'],['び','bi'],['ぶ','bu'],['べ','be'],['ぼ','bo'],
  ['ぱ','pa'],['ぴ','pi'],['ぷ','pu'],['ぺ','pe'],['ぽ','po'],
];
const yoonBases = [['き','ky'],['し','sh'],['ち','ch'],['に','ny'],['ひ','hy'],['み','my'],['り','ry'],['ぎ','gy'],['じ','j'],['び','by'],['ぴ','py']];
const smalls = [['ゃ','a'],['ゅ','u'],['ょ','o']];

const ROW_BOUNDS = [[5,'a'],[10,'k'],[15,'s'],[20,'t'],[25,'n'],[30,'h'],[35,'m'],[38,'y'],[43,'r'],[46,'w']];
const rowOf = i => ROW_BOUNDS.find(([n]) => i < n)[1];

const toKata = s => [...s].map(c => {
  const cp = c.codePointAt(0);
  return (cp >= 0x3041 && cp <= 0x3096) ? String.fromCodePoint(cp + 0x60) : c;
}).join('');

// Pedagogical notes, keyed by hiragana. Applied to the katakana twin as well where the point still holds.
const NOTES = {
  'う':'Not English "oo" — lips stay flat, not pushed forward.',
  'お':'A pure vowel. English "oh" glides into a w; this one holds still.',
  'し':'shi, never "si".',
  'す':'The u is often barely voiced after s — closer to "s" than "soo".',
  'ち':'chi, never "ti".',
  'つ':'tsu — the t and s are one sound. Hardest kana for English speakers.',
  'は':'As a topic particle this is pronounced wa, not ha.',
  'ふ':'Between f and h — blow gently, no bottom lip on teeth.',
  'へ':'As a direction particle this is pronounced e, not he.',
  'ら':'A quick tap of the tongue — between English r, l and d. Not an English r.',
  'り':'Same tap as ら.',
  'る':'Same tap as ら.',
  'れ':'Same tap as ら.',
  'ろ':'Same tap as ら.',
  'を':'Only used as the object particle, and pronounced o.',
  'ん':'A full beat of its own, and it changes shape: n, m or ng depending on what follows.',
  'ぢ':'Same sound as じ. Rare — じ is the normal spelling.',
  'づ':'Same sound as ず. Rare — ず is the normal spelling.',
};
const KATA_NOTES = {
  'ソ':'Easily confused with ン. ソ’s short stroke comes down from the top.',
  'ン':'Easily confused with ソ. ン’s short stroke sweeps up from the lower left.',
  'シ':'Easily confused with ツ. シ’s strokes come in from the left, low.',
  'ツ':'Easily confused with シ. ツ’s strokes come down from the top.',
  'ク':'Easily confused with ケ and タ.',
  'ー':'',
};
// Confusable pairs surfaced by the practice engine
const CONFUSABLES = {
  'あ':['お'],'お':['あ'],'ぬ':['め'],'め':['ぬ'],'る':['ろ'],'ろ':['る'],
  'は':['ほ'],'ほ':['は'],'き':['さ'],'さ':['き'],'れ':['わ','ね'],'わ':['れ','ね'],'ね':['れ','わ'],
  'ソ':['ン'],'ン':['ソ'],'シ':['ツ'],'ツ':['シ'],'ク':['ケ','タ'],'ケ':['ク'],'タ':['ク'],
  'ス':['ヌ'],'ヌ':['ス'],'ホ':['ボ'],'マ':['ム'],'ム':['マ'],
};

function build() {
  const rows = [];
  base.forEach(([kana, romaji], i) => rows.push({ kana, romaji, group: 'base', row: rowOf(i) }));
  voiced.forEach(([kana, romaji]) => rows.push({ kana, romaji, group: 'voiced', row: 'dakuten' }));
  for (const [k, stem] of yoonBases) {
    for (const [small, vowel] of smalls) {
      rows.push({ kana: k + small, romaji: stem + vowel, group: 'yoon', row: 'yoon' });
    }
  }

  const out = [];
  for (const r of rows) {
    out.push({
      id: `kana:h:${r.kana}`, script: 'hiragana', kana: r.kana, romaji: r.romaji,
      group: r.group, row: r.row,
      note: NOTES[r.kana] || null,
      confusables: (CONFUSABLES[r.kana] || []).map(c => `kana:h:${c}`),
    });
  }
  for (const r of rows) {
    const kana = toKata(r.kana);
    out.push({
      id: `kana:k:${kana}`, script: 'katakana', kana, romaji: r.romaji,
      group: r.group, row: r.row,
      note: KATA_NOTES[kana] || NOTES[r.kana] || null,
      confusables: (CONFUSABLES[kana] || (CONFUSABLES[r.kana] || []).map(toKata)).map(c => `kana:k:${c}`),
    });
  }
  return out;
}

const kana = build();
const header = `// GENERATED by tools/gen-kana.js — do not edit by hand.
// Romaji uses Hepburn (shi/chi/tsu/fu/ji), the romanisation Japanese learners meet in dictionaries.
// ${kana.filter(k => k.script === 'hiragana').length} hiragana + ${kana.filter(k => k.script === 'katakana').length} katakana.

export const KANA = ${JSON.stringify(kana, null, 1)};

export const KANA_BY_ID = Object.fromEntries(KANA.map(k => [k.id, k]));
`;
const target = path.join(__dirname, '..', 'src', 'content', 'kana.js');
fs.writeFileSync(target, header);
console.log(`wrote ${target}: ${kana.length} entries`);
